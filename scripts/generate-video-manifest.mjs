// Scans public/media/videos/** and writes src/lib/video-manifest.ts.
//
// The manifest is committed (and regenerated on `npm run build`) rather than
// read with `fs` at request time: on serverless hosts the contents of
// `public/` are served by the CDN and are not reliably readable from the
// function filesystem. Dropping a new .mp4 into one of the folders below and
// running `npm run videos:manifest` (or just building) is all it takes for the
// clip to show up in the admin dashboard as a private clip.

import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const FOLDERS = [
  { dir: "TikTok", category: "tiktok" },
  { dir: "clients", category: "clients" },
];

const VIDEO_EXTENSIONS = new Set([".mp4", ".webm", ".mov", ".m4v"]);

function scan() {
  const entries = [];

  for (const { dir, category } of FOLDERS) {
    const absolute = join(root, "public", "media", "videos", dir);
    if (!existsSync(absolute)) continue;

    const files = readdirSync(absolute)
      .filter((file) => VIDEO_EXTENSIONS.has(extname(file).toLowerCase()))
      .sort((a, b) => a.localeCompare(b));

    files.forEach((file, index) => {
      entries.push({
        // Encoded so filenames with spaces/apostrophes work as URLs.
        video_url: encodeURI(`/media/videos/${dir}/${file}`),
        // The filename is the source of truth for the default title — the
        // videos are named properly, so "Smooth Criminal Edit.mp4" becomes
        // "Smooth Criminal Edit" rather than "01".
        title: basename(file, extname(file)).trim(),
        category,
        sort_order: index,
      });
    });
  }

  return entries;
}

const entries = scan();

const file = `// AUTO-GENERATED by scripts/generate-video-manifest.mjs — do not edit by hand.
// Run \`npm run videos:manifest\` (or \`npm run build\`) after adding videos to
// public/media/videos/TikTok or public/media/videos/clients.

import type { PortfolioCategory } from "@/lib/types";

export type VideoManifestEntry = {
  video_url: string;
  title: string;
  category: PortfolioCategory;
  sort_order: number;
};

export const VIDEO_MANIFEST: VideoManifestEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(root, "src", "lib", "video-manifest.ts"), file);
console.log(`video manifest: ${entries.length} clip(s) written to src/lib/video-manifest.ts`);
